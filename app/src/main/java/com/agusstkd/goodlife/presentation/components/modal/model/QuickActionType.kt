package com.agusstkd.goodlife.presentation.components.modal.model

/**
 * Tipos de acciones rápidas en el modal del FAB.
 *
 * Define las categorías de registro rápido disponibles
 * desde el botón central de la aplicación.
 */
enum class QuickActionType {
    /** Registro de rutina de ejercicios */
    ROUTINE,
    /** Registro de alimentación */
    NUTRITION,
    /** Registro de peso corporal */
    WEIGHT,
    /** Registro de suplementos */
    SUPPLEMENTS,
    /** Registro de actividad física */
    ACTIVITY,
    /** Otras acciones */
    OTHER
}
